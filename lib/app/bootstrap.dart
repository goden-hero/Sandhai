/// Returns a visible failure screen if the selected Firebase mode cannot start.
Future<Widget> createApplication({
  AppConfig? config,
  Future<void> Function(AppConfig)? initializeFirebase,
}) async {
  AppConfig? selectedConfig;
  try {
    selectedConfig = config ?? AppConfig.fromEnvironment();
    AppConfig.current = selectedConfig;
    if (!selectedConfig.isDemo) {
      await (initializeFirebase ?? initializeFirebaseBackend)(selectedConfig)
          .timeout(const Duration(seconds: 20));
    }
    AuthService.configure();
    return SandhaiApp(isFirebaseConnected: !selectedConfig.isDemo);
  } catch (error, stackTrace) {
    debugPrint('Sandhai startup failed: $error\n$stackTrace');
    return StartupFailureApp(
      mode: selectedConfig?.mode.name ?? 'configuration',
      error: error.toString(),
    );
  }
}

Future<void> initializeFirebaseBackend(AppConfig config) async {
  if (config.isDemo) return;
  // FlutterFire remembers an emulator on localhost debug reloads. The explicit
  // current mode/host must take precedence over that previous-session hint.
  clearRememberedWebEmulator();

  final FirebaseOptions options;
  if (config.mode == AppMode.emulator) {
    // Independent of production options generated by FlutterFire.
    options = FirebaseOptions(
      apiKey: 'demo-api-key',
      appId: kIsWeb
          ? '1:1234567890:web:abcdef1234567890'
          : '1:1234567890:android:abcdef1234567890',
      messagingSenderId: '1234567890',
      projectId: config.emulatorProjectId,
      authDomain: '${config.emulatorProjectId}.firebaseapp.com',
      storageBucket: '${config.emulatorProjectId}.appspot.com',
    );
  } else {
    options = DefaultFirebaseOptions.currentPlatform;
    if (options.apiKey.startsWith('DEMO_') ||
        options.projectId == 'sandhai-5km-demo') {
      throw StateError(
        'Production Firebase configuration is missing. Run flutterfire configure '
        'for your Firebase project before selecting APP_MODE=production.',
      );
    }
  }

  if (config.mode == AppMode.emulator) {
    await prepareWebEmulatorAuth(options, config.emulatorHost);
  }
  await Firebase.initializeApp(options: options);
  // Auth persists across browser reloads; Firestore writes must be server-confirmed.
  FirebaseFirestore.instance.settings = const Settings(
    persistenceEnabled: false,
  );
  if (config.mode == AppMode.emulator) {
    if (!kIsWeb) {
      await FirebaseAuth.instance.useAuthEmulator(
        config.emulatorHost,
        9099,
        automaticHostMapping: false,
      );
    }
    // AppConfig already chooses 10.0.2.2 for an Android emulator. Preserve an
    // explicit loopback host for USB-forwarded physical devices as well.
    FirebaseFirestore.instance.useFirestoreEmulator(
      config.emulatorHost,
      8080,
      automaticHostMapping: false,
    );
    await FirebaseStorage.instance.useStorageEmulator(
      config.emulatorHost,
      9199,
      automaticHostMapping: false,
    );
  }
  // Configure emulators before restoring the web Auth session/token.
  if (kIsWeb) await FirebaseAuth.instance.setPersistence(Persistence.LOCAL);
}

class StartupFailureApp extends StatelessWidget {
  const StartupFailureApp({super.key, required this.mode, required this.error});

  final String mode;
  final String error;

  @override
  Widget build(BuildContext context) => MaterialApp(
    title: '5KM Sandhai — Startup error',
    debugShowCheckedModeBanner: false,
    theme: AppTheme.lightTheme,
    home: Scaffold(
      body: SafeArea(
        child: Center(
          child: SingleChildScrollView(
            padding: const EdgeInsets.all(24),
            child: ConstrainedBox(
              constraints: const BoxConstraints(maxWidth: 560),
              child: Column(
                mainAxisSize: MainAxisSize.min,
                children: [
                  const Icon(Icons.error_outline, size: 48),
                  const SizedBox(height: 16),
                  const Text(
                    'Unable to start 5KM Sandhai',
                    style: TextStyle(fontSize: 24, fontWeight: FontWeight.bold),
                    textAlign: TextAlign.center,
                  ),
                  const SizedBox(height: 12),
                  Text('Selected mode: $mode'),
                  const SizedBox(height: 12),
                  SelectableText(error),
                  const SizedBox(height: 16),
                  const Text(
                    'Check the selected mode and Firebase configuration, '
                    'then restart the application.',
                  ),
                ],
              ),
            ),
          ),
        ),
      ),
    ),
  );
}
